@lru_cache(maxsize=1)
def get_geo_tree() -> list[GeoNode]:
    """
    Полное дерево для каскадных селекторов фронта.
    Сортировка: страна → регионы → города → районы/метро.
    """
    nodes: list[GeoNode] = []

    # Россия (пока единственная страна)
    ru = GeoNode(
        id="ru", name="Россия", level=GeoLevel.COUNTRY,
        parent_id=None, search_hint="",
    )
    nodes.append(ru)

    for region, cities in _REGIONS.items():
        rid = _slug(region)
        nodes.append(GeoNode(
            id=rid, name=region, level=GeoLevel.REGION,
            parent_id="ru", search_hint=region,
        ))
        for city in cities:
            cid = _slug(f"{region}-{city}")
            hint = city if city in ("Москва", "Санкт-Петербург") else f"{city}"
            nodes.append(GeoNode(
                id=cid, name=city, level=GeoLevel.CITY,
                parent_id=rid, search_hint=hint,
            ))

            # Районы и метро (только для Москвы и Питера)
            if city == "Москва":
                _extend_with(nodes, cid, "msk-d", _MOSCOW_DISTRICTS,
                             GeoLevel.DISTRICT, "район")
                _extend_with(nodes, cid, "msk-m", _MOSCOW_METRO,
                             GeoLevel.METRO, "метро")
            elif city == "Санкт-Петербург":
                _extend_with(nodes, cid, "spb-d", _SPB_DISTRICTS,
                             GeoLevel.DISTRICT, "район")
                _extend_with(nodes, cid, "spb-m", _SPB_METRO,
                             GeoLevel.METRO, "метро")
            elif city in _OTHER_CITIES_DISTRICTS:
                _extend_with(nodes, cid, f"{cid}-d",
                             _OTHER_CITIES_DISTRICTS[city],
                             GeoLevel.DISTRICT, "район")

    return nodes


def _extend_with(
    nodes: list[GeoNode],
    parent_id: str,
    prefix: str,
    names: list[str],
    level: GeoLevel,
    suffix: str,
) -> None:
    for i, name in enumerate(names):
        nid = f"{prefix}-{i}"
        # Геопоисковая подсказка: «Москва, метро Александровский сад»
        parent_name = next(
            (n.name for n in nodes if n.id == parent_id), parent_id
        )
        hint = f"{parent_name}, {suffix} {name}" if level == GeoLevel.METRO \
            else f"{parent_name}, {name}"
        nodes.append(GeoNode(
            id=nid, name=name, level=level,
            parent_id=parent_id, search_hint=hint,
        ))


def _slug(text: str) -> str:
    """ASCII-slug с транслитерацией кириллицы — безопасен для URL/JSON."""
    import re as _re
    # Таблица транслитерации (ГОСТ 7.79-2000/B, упрощённая)
    tr = {
        "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e",
        "ё": "yo", "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k",
        "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
        "с": "s", "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "ts",
        "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "", "ы": "y", "ь": "",
        "э": "e", "ю": "yu", "я": "ya",
    }
    s = text.lower()
    s = "".join(tr.get(c, c) for c in s)
    s = _re.sub(r"[^a-z0-9]+", "-", s)
    return s.strip("-")


def build_search_hint(
    country_id: str = "ru",
    region_id: Optional[str] = None,
    city_id: Optional[str] = None,
    district_id: Optional[str] = None,
    metro_id: Optional[str] = None,
) -> str:
    """
    Собирает финальную гео-строку для запроса к Яндекс.Картам.
    Самый специфичный уровень «выигрывает»: метро перекрывает район.
    """
    tree = {n.id: n for n in get_geo_tree()}

    # Спускаемся от города вниз, чтобы собрать корректную фразу
    city = tree.get(city_id) if city_id else None
    if city is None:
        # без города берём регион
        region = tree.get(region_id) if region_id else None
        return region.search_hint if region else "Россия"

    metro = tree.get(metro_id) if metro_id else None
    district = tree.get(district_id) if district_id else None

    if metro:
        return metro.search_hint       # уже содержит «Москва, метро ...»
    if district:
        return district.search_hint    # «Москва, район Хамовники»
    return city.search_hint            # «Москва»


def dump_geo_tree_json(path: Path | str) -> None:
    """Сохранить дерево в JSON для фронта (чтобы не дёргать бэкенд)."""
    data = [n.model_dump(mode="json") for n in get_geo_tree()]
    Path(path).write_text(
        json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8"
    )


